#ifndef __WAVE_H
#define __WAVE_H

/************************* 头文件 *************************/

#include "HeaderFiles.h"

/************************* 宏定义 *************************/

/*
 * 调试波形：通过 UART8 把"当前速度"和"目标速度"发给上位机看波形。
 *
 * 采样在 TIM6 的 5ms 中断里做（只入队，不发送），发送在主循环里做。
 * 这样采样间隔严格 5ms，波形不会跟着主循环抖动；串口慢只会丢点，不影响控制。
 *
 * 串口输出格式（SerialPlot 的 ASCII 模式）：
 *     当前速度,目标速度\r\n        单位 转/秒，保留 3 位小数
 *   例："1.250,-0.800\r\n"
 *
 * SerialPlot 设置：Port 选 COMx → 115200 → Data Format 选 ASCII → 通道数自动识别为 2。
 */

/* 要观察的电机号（C620 拨码 ID） */
#ifndef WAVE_MOTOR_ID
#define WAVE_MOTOR_ID               2U
#endif

/* 环形缓冲深度：一帧 5ms，64 帧够撑过一次串口卡顿 */
#define WAVE_BUF_LEN                64U

/************************ 函数定义 ************************/

/* 清空缓冲，必须在 TIM6 中断启动之前调用 */
void Wave_Init(void);

/* 采一次当前速度 / 目标速度，只入队不发送；在 TIM6 的 5ms 中断里调 */
void Wave_Sample(void);

/* 缓冲里有数据就发一行出去；在主循环里调，一次最多发一行 */
void Wave_Send(void);

#endif

/****************************End*****************************/
